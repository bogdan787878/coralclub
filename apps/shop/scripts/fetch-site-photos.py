#!/usr/bin/env python3
"""
fetch-site-photos.py — download the product-gallery photos of the Friend-club
project's products from their real coralclub.us pages (the gallery images
carry the `buy-image` class), into public/images/products/us/<slug>-<n>.<ext>.

Usage:  python3 scripts/fetch-site-photos.py
"""
import hashlib
import json
import re
import sys
import urllib.request
from pathlib import Path

UA = {"User-Agent": "Mozilla/5.0"}
BASE = "https://coralclub.us"
OUT = Path(__file__).resolve().parent.parent / "public/images/products/us"

# the same picture at another crop that the hash cannot tell apart:
# (slug, position in the gallery after de-duplication) to leave out
SKIP = {("coral-mine-silver", 7), ("oceanmin", 7)}

# slug in our catalogue -> page on coralclub.us
PAGES = {
    "hydramax-plus": "hydramax-plus",
    "hydramax": "hydramax-europe",
    "coral-mine-silver": "coral-mine",
    "pentokan": "pentokan",
    "oceanmin": "oceanmin",
    "h-500": "h-500",
}


def get(url: str) -> bytes:
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return r.read()


def gallery(page: str) -> list[str]:
    html = get(f"{BASE}/shop/{page}.html").decode("utf8", "ignore")
    seen: list[str] = []
    for tag in re.findall(r"<(?:img|source)\b[^>]*>", html, re.I):
        if "buy-image" not in tag:
            continue
        for path in re.findall(r"(/upload/[^\"' ,]+\.(?:webp|jpe?g|png))", tag, re.I):
            if path not in seen:
                seen.append(path)
    return seen


def look(data: bytes) -> tuple[int, ...]:
    """A tiny perceptual hash: the same picture at another size gives the same value."""
    import io

    from PIL import Image

    im = Image.open(io.BytesIO(data)).convert("L").resize((9, 8))
    px = list(im.getdata())
    return tuple(int(px[r * 9 + c] > px[r * 9 + c + 1]) for r in range(8) for c in range(8))


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.iterdir():
        old.unlink()
    manifest: dict[str, list[str]] = {}
    for slug, page in PAGES.items():
        # the page repeats the same photo (thumbnails, colour variants): keep one of each
        seen: set[str] = set()
        shapes: list[tuple[int, ...]] = []
        n = 0
        pos = 0
        for path in gallery(page):
            data = get(BASE + path)
            digest = hashlib.sha1(data).hexdigest()
            shape = look(data)
            if digest in seen or any(
                sum(a != b for a, b in zip(shape, o)) <= 3 for o in shapes
            ):
                continue
            seen.add(digest)
            shapes.append(shape)
            pos += 1
            if (slug, pos) in SKIP:
                continue
            n += 1
            ext = path.rsplit(".", 1)[1].lower()
            target = OUT / f"{slug}-{n}.{ext}"
            target.write_bytes(data)
            name = target.name
            if ext == "png" and len(data) > 300_000:
                # heavy PNGs (multi-MB packshots) -> WebP
                from PIL import Image

                Image.open(target).save(target.with_suffix(".webp"), quality=86, method=6)
                target.unlink()
                name = target.with_suffix(".webp").name
            manifest.setdefault(slug, []).append(name)
        print(slug, n, "photos")
    out = OUT.parents[3] / "src/lib/friendPhotos.generated.ts"
    out.write_text(
        "// generated by scripts/fetch-site-photos.py — do not edit\n"
        "export const FRIEND_SITE_PHOTOS: Record<string, string[]> = "
        + json.dumps(manifest, indent=2)
        + ";\n"
    )


if __name__ == "__main__":
    sys.exit(main())
